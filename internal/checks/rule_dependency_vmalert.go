package checks

import (
	"strconv"
	"time"

	"github.com/cloudflare/pint/internal/discovery"
	"github.com/cloudflare/pint/internal/parser"
)

// vmalert writes recording rule results through remote write and every rule reads them
// with its own query, so a rule only sees results written before it runs. Rules in one
// group run at the same timestamp, so moving them into one group doesn't remove the lag,
// unlike in Prometheus. Groups can be chained with eval_offset instead, see "Chaining
// groups" in the vmalert docs. Checked with vmalert v1.153.0, groups evaluated every 1m:
//
//   - eval_offset 10s for the writer and 40s for the reader: the reader saw the result
//     written 30 seconds earlier, in the same cycle;
//   - writer and reader in the same group: the reader saw the result of the previous
//     evaluation;
//   - groups without eval_offset: the reader saw the result of the previous cycle.

// vmalertLatencyOffset is the default -search.latencyOffset of VictoriaMetrics, queries for
// the last 30 seconds are shifted back by it. The vmalert docs ask for eval_offset values at
// least that far apart.
const vmalertLatencyOffset = 30 * time.Second

// groupEvalOffset returns eval_offset of a group within [0, interval), or -1 if it's not set.
func groupEvalOffset(group *parser.Group, interval time.Duration) time.Duration {
	if group.VMAlert == nil || group.VMAlert.EvalOffset == nil {
		return -1
	}
	offset := *group.VMAlert.EvalOffset
	if offset < 0 {
		offset += interval
	}
	return offset
}

// isChainedGroup returns true if vmalert evaluates the reader group late enough after the
// writer group to see results of the same cycle: both groups set eval_offset, use the same
// interval and the reader runs at least vmalertLatencyOffset after the writer.
func isChainedGroup(writer, reader *discovery.Entry) bool {
	if writer.Group == nil || reader.Group == nil || writer.Group.Interval == nil || reader.Group.Interval == nil {
		return false
	}
	if writer.Group.Interval.ParseError != nil || reader.Group.Interval.ParseError != nil {
		return false
	}
	interval := writer.Group.Interval.Value
	if interval <= 0 || reader.Group.Interval.Value != interval {
		return false
	}
	w, r := groupEvalOffset(writer.Group, interval), groupEvalOffset(reader.Group, interval)
	if w < 0 || r < 0 {
		return false
	}
	return (r-w+interval)%interval >= vmalertLatencyOffset
}

func vmalertCrossGroupDetails(dep *crossGroupDep) string {
	return "This rule uses `" + dep.metric + "` which is generated by a recording rule in the `" + dep.group + "` group at `" + dep.path + ":" + strconv.Itoa(dep.line) + "`.\n" +
		"vmalert writes recording rule results through remote write and every rule reads them with its own query, " +
		"so this rule only sees results written before it runs, which can be the previous evaluation of `" + dep.group + "`, up to one interval old.\n" +
		"Moving both rules into the same group doesn't help with vmalert: rules in a group run at the same timestamp, " +
		"so they also only see results of the previous evaluation.\n" +
		"To see fresh results chain the groups: set the same `interval` and `eval_offset` on both groups, " +
		"with this rule's group evaluated at least 30s after `" + dep.group + "`, " +
		"see [chaining groups](https://docs.victoriametrics.com/victoriametrics/vmalert/#chaining-groups)."
}
